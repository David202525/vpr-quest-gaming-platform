function isLeaderP(p) { const a = p && p.account; return !!(a && (Number(a.leader) === 1 || Number(a.job_rank) >= 10)); }
function isMgr(p) { const G = global.GovFaction; return isLeaderP(p) || !!(G && G.canManage && G.canManage(p)); }
function inFac(list) { return function (p) { return list.indexOf(job(p)) >= 0; }; }
function isGovName(p) { return job(p) === 'gov'; }
function isGovernor(p) { return isGovName(p) && isLeaderP(p); }

function CR() { return global.CrimeSystem; }
function inOrg(t) { return function (p) { const C = CR(); const k = job(p); return !!(C && C.ORGS[k] && (!t || C.ORGS[k].t === t)); }; }
function orgMgr(p) { const C = CR(); return inOrg()(p) && (isLeaderP(p) || (C && C.O(job(p)).deps.indexOf(Number(p.account.id)) >= 0)); }

