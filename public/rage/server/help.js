function show(p, title, rows) {
    p.outputChatBox('!{#ffd24d}--- ' + title + ' ---');
    rows.forEach(function (r) {
        if (!r[0]) p.outputChatBox('!{#cccccc}' + r[1]);
        else p.outputChatBox('!{#7fd4ff}' + r[0] + ' !{#cccccc}- ' + r[1]);
    });
}

mp.events.addCommand('help', function (p, arg) {
    const list = SECTIONS.filter(function (s) { return s.can(p); });
    const n = parseInt(arg, 10);
    const ON = CR() && CR().ORGS[job(p)] ? CR().ORGS[job(p)].n : null;
    if (ON) FNAME[job(p)] = ON;
    if (!isNaN(n) && list[n - 1]) return show(p, list[n - 1].title, list[n - 1].rows);
    const q = String(arg || '').trim().toLowerCase();
    if (q === 'all' || q === 'фракции') {
        p.outputChatBox('!{#ffd24d}=== Фракции сервера ===');
        [['Банды: Ballas · Families · Vagos · Marabunta · Bloods', 'захват районов, доход в общак'], ['Мафии: La Cosa Nostra · Русская · Yakuza', 'поставки укропа и нелегального оружия'], ['LSPD · Шериф · FIB', 'розыск, аресты, штрафы, проверка прав, обыск'], ['EMS', 'лечение, вызовы /911'], ['Армия', 'поставки оружия на склады'], ['Правительство', 'казна, налоги, зарплаты, гос. новости'], ['Weazel News', 'новости штата'], ['Лицензионный центр', 'экзамены на права B/C/D']].forEach(function (r) { p.outputChatBox('!{#7fd4ff}' + r[0] + ' !{#cccccc}- ' + r[1]); });
        p.outputChatBox('!{#cccccc}Вступить: приглашение от лидера или заместителя (Y — принять). Набор объявляется через /gov');
        return;
    }
    if (q && isNaN(n)) {
        const hits = [];
        SECTIONS.forEach(function (s) { s.rows.forEach(function (r) { if ((r[0] + ' ' + r[1]).toLowerCase().indexOf(q) >= 0) hits.push([r[0], r[1] + ' !{#888888}(' + s.title + ')']); }); });
        if (!hits.length) return p.outputChatBox('!{#ffcc66}Ничего не найдено по «' + q + '»');
        return show(p, 'Поиск: ' + q, hits.slice(0, 14));
    }
    if (list.length === 1) {
        show(p, list[0].title, list[0].rows);
    } else {
        p.outputChatBox('!{#ffd24d}=== Помощь по серверу ===' + (job(p) && FNAME[job(p)] ? ' !{#cccccc}· ваша фракция: !{#ffffff}' + FNAME[job(p)] : ''));
        list.forEach(function (s, i) {
            p.outputChatBox('!{#7fd4ff}/help ' + (i + 1) + ' !{#ffffff}- ' + s.title);
        });
        p.outputChatBox('!{#cccccc}/help all — все фракции · /help [название] — поиск, например /help рация');
    }
    if (lvl(p) >= 1) p.outputChatBox('!{#ff8080}/ahelp !{#ffffff}- команды администратора');
});

mp.events.addCommand('ahelp', function (p, arg) {
    const my = lvl(p);
    if (my < 1) return;
    const list = ADMIN.filter(function (s) { return my >= s[0]; });
    const n = parseInt(arg, 10);
    if (!isNaN(n) && list[n - 1]) return show(p, list[n - 1][1], list[n - 1][2]);
    p.outputChatBox('!{#ff8080}=== Админ-команды: ' + rankName(my) + ' (уровень ' + my + ') ===');
    list.forEach(function (s, i) {
        p.outputChatBox('!{#7fd4ff}/ahelp ' + (i + 1) + ' !{#ffffff}- ' + s[1]);
    });
    p.outputChatBox('!{#cccccc}Тебе доступны все команды уровня ' + my + ' и ниже');
    if (!list.length) p.outputChatBox('!{#cccccc}Для твоего уровня команд пока нет');
});

